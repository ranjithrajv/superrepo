/**
 * Generate docs/CATALOG.md — the public catalog, readable without installing
 * anything.
 *
 * The point is public signal. It answers, from the repo alone:
 *
 *   - what is listed, and what each rewrite rule actually produces
 *   - what a row gives each service when you're on a file vs a folder vs the root
 *   - when it was last probed, and what the probe found
 *
 * Everything here comes from src/catalog.js and, when present, a probe report
 * written by `npm run probe -- --out probe-report.json`. No telemetry, no server:
 * it is a file in the repository, diffable in a PR like any other change.
 *
 *   node scripts/gen-catalog-page.mjs
 *   node scripts/gen-catalog-page.mjs --check
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { CATALOG, CATEGORIES, buildTarget, allServices } from "../src/catalog.js";
import { parseRepoUrl } from "../src/parse.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FILE = join(ROOT, "docs/CATALOG.md");
const REPORT = join(ROOT, "probe-report.json");
const BEGIN = "<!-- BEGIN:generated -->";
const END = "<!-- END:generated -->";

/**
 * A stable public repo, so the examples below are real and comparable.
 *
 * The file example is deliberately nested. A file at the repo root has the repo
 * root as its containing folder, which makes the file→folder narrowing invisible
 * exactly where you would most want to show it off.
 */
const SAMPLE = "github.com/coderamp-labs/gitingest";
const PAGES = {
  repo: `https://${SAMPLE}`,
  folder: `https://${SAMPLE}/tree/main/src/gitingest`,
  file: `https://${SAMPLE}/blob/main/src/gitingest/ingestion.py`,
};

/** Which slice of the repo a row receives, derived from the built target. */
function sliceOf(target, ctx) {
  if (target?.kind === "command") return "a command";
  const url = target?.url;
  if (!url) return "—";
  if (!ctx.path) return "the repo";
  let decoded = url;
  try {
    decoded = decodeURIComponent(url);
  } catch {
    /* compare as-is */
  }
  if (decoded.includes(ctx.path)) return ctx.type === "tree" ? "this folder" : "this file";
  const slash = ctx.path.lastIndexOf("/");
  const dir = slash === -1 ? "" : ctx.path.slice(0, slash);
  if (dir && decoded.includes(dir)) return "this folder";
  return "the repo";
}

const STATE_MARK = {
  ok: "ok",
  "ok-aliased": "ok (alias)",
  "http-error": "http error",
  unreachable: "**unreachable**",
};

async function loadReport() {
  try {
    const raw = await readFile(REPORT, "utf8");
    const parsed = JSON.parse(raw);
    return { ...parsed, byId: new Map(parsed.results.map((r) => [r.id, r])) };
  } catch {
    return null;
  }
}

function buildPage(report) {
  const generated = report?.generated
    ? new Date(report.generated).toISOString().slice(0, 10)
    : null;
  const probeLine = report
    ? `Last probed **${generated}** — ${report.summary.ok} ok, ${report.summary.aliased} aliased, ` +
      `${report.summary.httpError} http error, ${report.summary.unreachable} unreachable.`
    : "No probe report yet. Run `npm run probe -- --out probe-report.json`.";

  const lines = [
    `<!-- Generated by scripts/gen-catalog-page.mjs from src/catalog.js. Edit the catalog, not this. -->`,
    "",
    `Everything SuperRepo links to, and exactly what it sends each service. Generated from the`,
    `same data the extension ships, so it cannot describe a tool the button doesn't offer.`,
    "",
    `Examples below are built for **${SAMPLE}**. Probe status: ${probeLine}`,
    "",
    `> Tool owners: this file is generated. To change a row, edit \`src/catalog.js\` and run`,
    `> \`npm run partners\`. To be added at all, use the`,
    `> [*List my service* issue template](../.github/ISSUE_TEMPLATE/partners.yml) — one working URL is enough.`,
    "",
  ];

  for (const category of CATEGORIES) {
    const services = allServices().filter((s) => s.category === category.id);
    if (!services.length) continue;

    lines.push(`## ${category.label}`, "");

    for (const service of services) {
      const rows = Object.entries(PAGES).map(([page, url]) => {
        const ctx = parseRepoUrl(url);
        const target = buildTarget(service, ctx);
        const slice = sliceOf(target, ctx);
        const shown = target?.kind === "url" ? target.url : target?.command || "—";
        return `| ${page} | ${slice} | \`${shown.replace(/\|/g, "\\|")}\` |`;
      });

      const reportRow = report?.byId?.get(service.id);
      const status = reportRow
        ? `${STATE_MARK[reportRow.state] || reportRow.state}${reportRow.note ? ` — ${reportRow.note}` : ""}`
        : "not probed";

      lines.push(
        `### ${service.name}`,
        "",
        `${service.blurb} · **${category.label}**${service.docs ? ` · [${service.docs.replace(/^https?:\/\//, "")}](${service.docs})` : ""}`,
        "",
        `Probe: ${status}`,
        "",
        "| Page | Gets | Target |",
        "| --- | --- | --- |",
        ...rows,
        "",
      );
    }
  }

  lines.push(
    "---",
    "",
    "Names, marks and URLs belong to their owners. SuperRepo is an independent tool: not",
    "affiliated with, endorsed by, or connected to GitHub or any service listed above.",
    "",
  );

  return lines.join("\n");
}

/**
 * Strip probe-derived lines so the drift gate compares only what the catalog
 * determines.
 *
 * The page carries a probe timestamp and a per-service status, and that data
 * comes from probe-report.json — which is gitignored, because the weekly job
 * regenerates it and a committed copy would be a date that goes stale on its
 * own. Without this normalisation, a fresh clone regenerates the page with no
 * report and `npm run check` fails on a diff that says nothing about the
 * catalog.
 *
 * What is gated is therefore exactly the part that could misrepresent the
 * product: the rewrite rules, the targets, the slices, the blurbs and the
 * links. Those must match the catalog exactly, every time. The probe overlay
 * is best-effort and may be absent.
 */
function withoutProbeOverlay(text) {
  return text
    .split("\n")
    .filter((line) => !/^Probe: /.test(line) && !/^Examples below are built for /.test(line))
    .join("\n");
}

async function main() {
  const check = process.argv.includes("--check");
  const report = await loadReport();

  const missing = CATALOG.filter((s) => !s.docs);
  if (missing.length) {
    console.error(`✗ ${missing.map((s) => s.id).join(", ")}: no \`docs\` URL`);
    process.exit(1);
  }

  let source;
  try {
    source = await readFile(FILE, "utf8");
  } catch {
    // First run: the file may not exist yet.
    source = `# Catalog\n\n${BEGIN}\n${END}\n`;
  }

  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    console.error(`✗ ${FILE} is missing the ${BEGIN} / ${END} markers`);
    process.exit(1);
  }

  const header = source.slice(0, start + BEGIN.length);
  const footer = source.slice(end);
  const next = `${header}\n${buildPage(report)}\n${footer}`;

  if (check) {
    if (withoutProbeOverlay(next) === withoutProbeOverlay(source)) {
      console.log("· docs/CATALOG.md matches src/catalog.js");
      return;
    }
    console.error("\n✗ docs/CATALOG.md is out of date with src/catalog.js.\n  Run: npm run catalog\n");
    process.exit(1);
  }

  await writeFile(FILE, next);
  const state = report ? ` (probe ${report.generated.slice(0, 10)})` : " (no probe report yet)";
  console.log(`✓ docs/CATALOG.md written${state}`);
}

main().catch((error) => {
  console.error(`✗ ${error.message}`);
  process.exit(1);
});